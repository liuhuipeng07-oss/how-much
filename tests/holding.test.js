const assert = require('assert')
const { calendarTime, holdingStats } = require('../utils/holding')
assert.strictEqual(calendarTime('2026-02-30'), null)
assert.strictEqual(calendarTime('2026-2-01'), null)
assert.strictEqual(holdingStats({ cost: 300, acquiredAt: '2026-10-23' }, '2026-10-26').dailyCostText, '100.00')
assert.strictEqual(holdingStats({ cost: 300, acquiredAt: '2026-10-26' }, '2026-10-26').holdingDays, 1)
assert.strictEqual(holdingStats({ cost: 0, acquiredAt: '2026-10-26' }, '2026-10-26').dailyCostText, '0.00')
assert.strictEqual(holdingStats({ cost: 100, createdAt: '2020-01-01' }, '2026-10-26').hasHoldingDate, false)
assert.strictEqual(holdingStats({ cost: 100, acquiredAt: '2026-10-27' }, '2026-10-26').hasHoldingDate, false)
assert.strictEqual(holdingStats({ cost: 200, acquiredAt: '2024-02-28' }, '2024-03-01').holdingDays, 2)
assert.strictEqual(holdingStats({ cost: 100, acquiredAt: '2025-12-31' }, '2026-01-01').holdingDays, 1)
console.log('Holding tests passed: natural days, leap years, missing/future dates, zero cost')
